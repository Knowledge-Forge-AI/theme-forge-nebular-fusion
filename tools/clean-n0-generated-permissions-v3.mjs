import { createHash } from "node:crypto";
import { lstat, readFile, readdir, unlink } from "node:fs/promises";
import { isAbsolute, resolve } from "node:path";

const DIRECTORY = "src-tauri/permissions/autogenerated";
const BASELINE = "tools/n0-generated-permission-baseline-v3.json";
const HEX64 = /^[a-f0-9]{64}$/u;

function fail(code) {
  throw new Error(`N0_GENERATED_CLEAN_${code}`);
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function readBaseline(root) {
  let value;
  try {
    value = JSON.parse(await readFile(resolve(root, BASELINE), "utf8"));
  } catch {
    fail("BASELINE_READ");
  }
  if (!value || typeof value !== "object" || Array.isArray(value) || JSON.stringify(Object.keys(value).sort()) !== JSON.stringify(["count", "files", "schema"])) fail("BASELINE_SHAPE");
  if (value.schema !== "theme-forge.native-n0-generated-baseline.v1" || value.count !== 49 || !Array.isArray(value.files)) {
    fail("BASELINE_SHAPE");
  }
  if (value.files.length !== value.count) fail("BASELINE_COUNT");
  const paths = new Set();
  for (const file of value.files) {
    if (!file || typeof file !== "object" || Array.isArray(file) || JSON.stringify(Object.keys(file).sort()) !== JSON.stringify(["bytes", "path", "sha256"])) fail("BASELINE_ENTRY");
    if (typeof file.path !== "string" || !file.path.startsWith(`${DIRECTORY}/`) || file.path.includes("..")) {
      fail("BASELINE_PATH");
    }
    if (paths.has(file.path) || !Number.isInteger(file.bytes) || file.bytes < 1 || file.bytes > 64 * 1024 || !HEX64.test(file.sha256)) {
      fail("BASELINE_ENTRY");
    }
    paths.add(file.path);
  }
  return value.files;
}

export async function clearN0GeneratedPermissions(root) {
  if (typeof root !== "string" || !isAbsolute(root)) fail("ROOT");
  const files = await readBaseline(root);
  const directory = resolve(root, DIRECTORY);
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    fail("DIRECTORY_READ");
  }
  const expectedNames = new Set(files.map((file) => file.path.slice(`${DIRECTORY}/`.length)));
  if (entries.length !== files.length || entries.some((entry) => !expectedNames.has(entry.name))) fail("DIRECTORY_SET");
  for (const file of files) {
    const absolutePath = resolve(root, file.path);
    let stat;
    let bytes;
    try {
      stat = await lstat(absolutePath);
      bytes = await readFile(absolutePath);
    } catch {
      fail("FILE_READ");
    }
    if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1 || stat.size !== file.bytes || bytes.length !== file.bytes || sha256(bytes) !== file.sha256) {
      fail("FILE_IDENTITY");
    }
  }
  for (const file of files) await unlink(resolve(root, file.path));
  const remaining = await readdir(directory);
  if (remaining.length !== 0) fail("NOT_EMPTY");
  return { count: files.length, directory: DIRECTORY };
}

function parseArgs(argv) {
  if (argv.length !== 2 || argv[0] !== "--root" || !argv[1]) fail("CLI_ARGUMENTS");
  return argv[1];
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const result = await clearN0GeneratedPermissions(parseArgs(process.argv.slice(2)));
  process.stdout.write(`${JSON.stringify(result)}\n`);
}
